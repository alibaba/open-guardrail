package run

import (
	"strings"
	"unicode/utf8"
)

// ValidBusinessID validates a caller-owned identifier without normalizing it.
func ValidBusinessID(value string) bool {
	if value == "" || len(value) > 128 || !utf8.ValidString(value) || strings.TrimSpace(value) != value {
		return false
	}
	for _, r := range value {
		if r < 0x20 || r == 0x7f {
			return false
		}
	}
	return true
}
