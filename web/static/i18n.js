const languageStorageKey = "open-guardrail.language";

function initialLanguage() {
  try {
    const saved = localStorage.getItem(languageStorageKey);
    if (Object.hasOwn(translations, saved)) return saved;
  } catch { /* Storage may be disabled; language switching still works. */ }
  const preferred = (navigator.languages || [navigator.language])[0] || "en";
  return /^zh(?:-|$)/i.test(preferred) ? "zh-CN" : "en";
}

let language = initialLanguage();
function t(key) {
  return translations[language][key] ?? translations.en[key] ?? key;
}

function applyLanguage() {
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach(element => {
    element.textContent = t(element.dataset.i18n);
  });
  document.querySelector("#language").value = language;
  if (typeof window !== "undefined") window.RunUI?.refreshLanguage();
}

function setText(element, key) {
  element.dataset.i18n = key;
  element.textContent = t(key);
}

document.querySelector("#language").addEventListener("change", event => {
  if (!Object.hasOwn(translations, event.target.value)) return;
  language = event.target.value;
  try { localStorage.setItem(languageStorageKey, language); } catch { /* Optional preference. */ }
  applyLanguage();
});
applyLanguage();
